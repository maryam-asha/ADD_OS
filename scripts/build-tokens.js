// 3. Flutter / Dart transformer
// ════════════════════════════════════════════════════════════════════════════

function buildDart() {
	const hexToDart = h => {
		const v = String(h).replace("#", "")
		return v.length === 6 ? `0xFF${v.toUpperCase()}` : `0xFF${v.slice(0, 6).toUpperCase()}`
	}
	const isHex = v => typeof v === "string" && v.startsWith("#")
	const L = semantic.light
	const out = []

	out.push("// ignore_for_file: constant_identifier_names")
	out.push(`// ${banner("this file")}`)
	out.push("// Source: src/add-os/theme/tokens.ts\n")
	out.push("import 'dart:ui';\n")
	out.push("/// ADD OS brand primitives — verbatim from the ADD Brand Guideline 2026.")
	out.push("class AddBrand {")
	out.push("  AddBrand._();")
	for (const [k, v] of Object.entries(brand)) out.push(`  static const Color ${k} = Color(${hexToDart(v)});`)
	out.push("}\n")

	out.push("/// ADD OS semantic tokens — light mode.")
	out.push("/// Dark mode is out of scope for v1; add an `AddColorsDark` class when it lands.")
	out.push("class AddColors {")
	out.push("  AddColors._();")
	for (const [role, v] of Object.entries(L)) {
		if (isHex(v)) {
			out.push(`  static const Color ${role} = Color(${hexToDart(v)});`)
			continue
		}
		if (v && typeof v === "object") {
			for (const [sub, hex] of Object.entries(v)) {
				if (!isHex(hex)) continue
				const name = role + sub.charAt(0).toUpperCase() + sub.slice(1)
				out.push(`  static const Color ${name} = Color(${hexToDart(hex)});`)
			}
		}
	}
	out.push("}\n")

	out.push("/// Per-language type scale. Arabic runs larger and looser than Latin.")
	out.push("class AddTypeScale {")
	out.push("  AddTypeScale._();")
	for (const lang of SUPPORTED_LANGS) {
		for (const [step, v] of Object.entries(typeScale[lang])) {
			const n = `${lang}_${step}`
			out.push(`  static const double ${n}Size = ${Number.parseFloat(v.fontSize)};`)
			out.push(`  static const double ${n}LineHeight = ${Number.parseFloat(v.lineHeight)};`)
		}
	}
	out.push("}\n")

	out.push("class AddRadius {")
	out.push("  AddRadius._();")
	for (const [k, v] of Object.entries(radius)) out.push(`  static const double ${k} = ${Number.parseFloat(v)};`)
	out.push("}\n")

	out.push("class AddSpace {")
	out.push("  AddSpace._();")
	for (const [k, v] of Object.entries(space)) out.push(`  static const double s${k} = ${Number.parseFloat(v)};`)
	out.push("}")

	return out.join("\n")
}

