// 4. Figma Tokens transformer  →  figma-tokens.json
// 5. Pinx runtime transformer   →  src/design-tokens.json
//
// Both must match the schema `src/theme/index.ts` already reads, so nothing
// downstream changes shape — only the values do.
//
// ── colors.dark is deliberately a COPY of colors.light ──────────────────────
// `getDefaultState()` picks Dark when the OS prefers dark, and `themeName` is
// persisted. Shipping a dark palette is out of scope, so a genuinely dark set
// here would render as a half-themed dark mode — exactly what was ruled out.
// Mirroring light means no configuration can produce an unthemed screen.
// The theme is ALSO pinned to Light at its source; this is the second belt.
// ════════════════════════════════════════════════════════════════════════════

function runtimeColors() {
	const L = semantic.light
	return {
		sidebarBackground: component.light.sidebar.background,
		bodyBackground: L.body,
		background: L.surface,
		backgroundSecondary: L.surfaceSunken,
		text: L.textPrimary,
		textSecondary: L.textSecondary,
		textTertiary: L.textMuted,
		border: L.border,
		hover: component.light.sidebar.itemHoverBackground,
		primary: L.primary.base,
		info: L.info.base,
		success: L.success.base,
		warning: L.warning.base,
		// Pinx names this slot `error`; ADD OS calls the role `danger`.
		error: L.danger.base,
		// Categorical data-viz slots — the brand colours left unassigned by Tier 2.
		extra1: brand.deepTeal,
		extra2: brand.smartOlive,
		extra3: brand.antiqueCopper,
		extra4: brand.softGrowthGreen
	}
}

/** Latin is the baseline for the runtime scale; :lang(ar) overrides it in CSS. */
const RUNTIME_LANG = "en"

function buildRuntimeTokens() {
	const s = typeScale[RUNTIME_LANG]
	const colors = runtimeColors()

	return {
		// JSON carries no comments, so the banner is a key. `src/theme/index.ts`
		// reads this file by named property, so an extra one is inert.
		$generated: banner("this file"),
		borderRadius: { default: radius.default, small: radius.small },
		lineHeight: { default: s.body.lineHeight },
		fontSize: { default: s.body.fontSize, cardTitle: s.lead.fontSize },
		fontWeight: {
			default: fontWeight.regular,
			strong: fontWeight.strong,
			cardTitle: fontWeight.strong
		},
		fontFamily: { default: fontFamily.ui, display: fontFamily.display, mono: fontFamily.mono },
		typography: {
			h1: { fontFamily: "{fontFamily.display}", fontSize: s.h1.fontSize, fontWeight: fontWeight.bold },
			h2: { fontFamily: "{fontFamily.display}", fontSize: s.h2.fontSize, fontWeight: fontWeight.bold },
			h3: { fontFamily: "{fontFamily.display}", fontSize: s.h3.fontSize, fontWeight: fontWeight.bold },
			h4: { fontFamily: "{fontFamily.display}", fontSize: s.h4.fontSize, fontWeight: fontWeight.strong },
			h5: { fontFamily: "{fontFamily.display}", fontSize: s.h5.fontSize, fontWeight: fontWeight.strong },
			h6: { fontFamily: "{fontFamily.default}", fontSize: s.h6.fontSize, fontWeight: fontWeight.medium },
			p: { fontFamily: "{fontFamily.default}", fontSize: "{fontSize.default}", lineHeight: s.body.lineHeight }
		},
		colors: { light: colors, dark: { ...colors } }
	}
}

function buildFigmaTokens() {
	const r = buildRuntimeTokens()
	const global = {
		"border-radius-default": { value: r.borderRadius.default, type: "borderRadius" },
		"border-radius-small": { value: r.borderRadius.small, type: "borderRadius" },
		"line-heights-default": { value: r.lineHeight.default, type: "lineHeights" },
		"font-sizes-default": { value: r.fontSize.default, type: "fontSizes" },
		"font-sizes-card-title": { value: r.fontSize.cardTitle, type: "fontSizes" },
		"font-weights-default": { value: r.fontWeight.default, type: "fontWeights" },
		"font-weights-strong": { value: r.fontWeight.strong, type: "fontWeights" },
		"font-weights-card-title": { value: r.fontWeight.cardTitle, type: "fontWeights" },
		"font-families-default": { value: r.fontFamily.default, type: "fontFamilies" },
		"font-families-display": { value: r.fontFamily.display, type: "fontFamilies" },
		"font-families-mono": { value: r.fontFamily.mono, type: "fontFamilies" }
	}

	for (const mode of ["light", "dark"]) {
		for (const [k, v] of Object.entries(r.colors[mode])) {
			global[`color-${mode}-${kebab(k)}`] = { value: v, type: "color" }
		}
	}
	for (const [tag, v] of Object.entries(r.typography)) {
		global[`typo-${tag}`] = { value: { ...v }, type: "typography" }
	}

	const ref = mode =>
		Object.fromEntries(
			Object.keys(r.colors[mode]).map(k => [`color-${kebab(k)}`, { value: `{color-${mode}-${kebab(k)}}`, type: "color" }])
		)

	// `$metadata` is Tokens Studio's own key, so the banner rides along in a slot
	// the plugin already understands rather than showing up as a stray token set.
	// `tokens-tool.js` reads only .global/.light/.dark, so it is inert there too.
	return {
		$metadata: {
			generated: banner("this file"),
			tokenSetOrder: ["global", "light", "dark"]
		},
		global,
		light: ref("light"),
		dark: ref("dark")
	}
}

